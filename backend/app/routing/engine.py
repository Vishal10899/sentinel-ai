"""Adaptive AI Routing Engine Facade composing the entire 10-step routing pipeline."""

from dataclasses import dataclass, field
from decimal import Decimal

from app.cost import CostCalculator
from app.routing.analyzer import PromptAnalysisResult, prompt_analyzer
from app.routing.classifier import TaskCategoryV2, task_classifier
from app.routing.complexity import ComplexityLevel, complexity_analyzer
from app.routing.scoring import CandidateScoreBreakdown, scoring_engine
from app.routing.types import ModelInfo


@dataclass(frozen=True, slots=True)
class FullRoutingDecision:
    """Complete, structured decision output generated by the Adaptive Routing Engine."""

    selected_provider: str
    selected_model: str
    strategy_used: str
    primary_reason: str
    intent_detected: str
    intent_confidence: float
    complexity_level: str
    complexity_score: float
    estimated_cost_usd: Decimal
    estimated_latency_ms: int
    estimated_savings_pct: float
    ranked_candidates: tuple[CandidateScoreBreakdown, ...]
    rejected_providers: tuple[str, ...]
    alternative_models: tuple[str, ...]
    failover_triggered: bool = False

    def to_dict(self) -> dict:
        return {
            "selected_provider": self.selected_provider,
            "selected_model": self.selected_model,
            "strategy_used": self.strategy_used,
            "primary_reason": self.primary_reason,
            "intent_detected": self.intent_detected,
            "intent_confidence": self.intent_confidence,
            "complexity_level": self.complexity_level,
            "complexity_score": self.complexity_score,
            "estimated_cost_usd": float(self.estimated_cost_usd),
            "estimated_latency_ms": self.estimated_latency_ms,
            "estimated_savings_pct": self.estimated_savings_pct,
            "ranked_candidates": [c.to_dict() for c in self.ranked_candidates],
            "rejected_providers": list(self.rejected_providers),
            "alternative_models": list(self.alternative_models),
            "failover_triggered": self.failover_triggered,
        }


class AdaptiveAIRoutingEngine:
    """Enterprise 10-step Adaptive AI Routing Engine."""

    def __init__(self) -> None:
        self.analyzer = prompt_analyzer
        self.classifier = task_classifier
        self.complexity_engine = complexity_analyzer
        self.scoring_engine = scoring_engine
        self.cost_calculator = CostCalculator()

        # GPT-4o baseline pricing ($/1K tokens) for cost savings estimation
        self._gpt4o_baseline_cost = 0.0025

    def route(
        self,
        prompt: str,
        system_prompt: str = "",
        has_attachments: bool = False,
        has_images: bool = False,
        strategy: str = "balanced",
        candidates: list[ModelInfo] | None = None,
        max_completion_tokens: int = 500,
    ) -> FullRoutingDecision:
        """Execute complete 10-step routing pipeline."""
        text = prompt.strip()

        # Step 1: Prompt Analysis
        analysis: PromptAnalysisResult = self.analyzer.analyze(
            text, system_prompt=system_prompt, has_attachments=has_attachments, has_images=has_images
        )

        # Step 2: Task Classification
        classification = self.classifier.classify(
            text, detected_language=analysis.detected_language, has_attachments=has_attachments
        )

        # Step 3: Complexity Analysis
        complexity = self.complexity_engine.analyze(
            text,
            estimated_tokens=analysis.estimated_tokens,
            reasoning_depth=analysis.reasoning_depth,
            has_code=analysis.has_code,
            has_files=analysis.has_files,
            has_math=analysis.has_math,
        )

        # Step 4 & 5: Model Capability Matching & Provider Health Check
        pool = candidates or []
        active_candidates: list[ModelInfo] = []
        rejected_providers: list[str] = []

        for m in pool:
            # Filter unhealthy or explicitly disabled providers
            if m.provider_status in ("unhealthy", "disabled", "DOWN") or getattr(m, "provider_failures", 0) >= 3:
                rejected_providers.append(f"{m.provider}/{m.model_name} (Status: {m.provider_status})")
                continue

            # Modality filter
            if analysis.has_images and not getattr(m, "supports_vision", False):
                rejected_providers.append(f"{m.provider}/{m.model_name} (No Vision Support)")
                continue

            active_candidates.append(m)

        failover_triggered = False
        if not active_candidates:
            # Fallback to configured/enabled candidates if specific modality filters excluded all models
            active_candidates = [
                m for m in pool
                if m.provider_status not in ("disabled", "unconfigured", "unhealthy", "DOWN")
            ]
            failover_triggered = True

        if not active_candidates:
            raise ValueError(f"No available or compatible models for task '{classification.primary_category.value}'")

        # Step 6, 7 & 8: Cost & Latency Estimation, Candidate Ranking & Weighted Scoring
        ranked_scores = self.scoring_engine.evaluate(
            active_candidates,
            task_category=classification.primary_category,
            complexity=complexity.level,
            strategy_name=strategy,
        )

        # Step 9: Best Model Selection
        selected = ranked_scores[0]
        selected_model_info = next(
            (m for m in active_candidates if m.provider == selected.provider_id and m.model_name == selected.model_id),
            active_candidates[0],
        )

        # Cost & Latency estimation
        est_cost = self.cost_calculator.calculate_token_costs(
            analysis.estimated_tokens,
            max_completion_tokens,
            Decimal(str(selected_model_info.cost_per_1k_tokens / 2.0)),
            Decimal(str(selected_model_info.cost_per_1k_tokens / 2.0)),
        )

        # Savings vs GPT-4o baseline
        baseline_cost = (analysis.estimated_tokens / 1000.0) * self._gpt4o_baseline_cost
        actual_cost_val = float(est_cost)
        if baseline_cost > 0 and actual_cost_val < baseline_cost:
            est_savings = round(((baseline_cost - actual_cost_val) / baseline_cost) * 100.0, 1)
        else:
            est_savings = 0.0

        # Primary Rationale string
        primary_reason = (
            f"Selected {selected.provider_id}/{selected.model_id} (Score: {selected.overall_score}/100) "
            f"for {classification.primary_category.value} ({complexity.level.value} complexity). "
            f"Model offers {selected_model_info.latency}ms SLA latency, ${selected_model_info.cost_per_1k_tokens}/1K token rate, "
            f"and {selected_model_info.quality_score}% quality score."
        )

        alt_models = [f"{c.provider_id}/{c.model_id}" for c in ranked_scores[1:4]]

        # Step 10: Return Full Decision
        return FullRoutingDecision(
            selected_provider=selected.provider_id,
            selected_model=selected.model_id,
            strategy_used=strategy,
            primary_reason=primary_reason,
            intent_detected=classification.primary_category.value,
            intent_confidence=classification.confidence,
            complexity_level=complexity.level.value,
            complexity_score=complexity.score_1_to_10,
            estimated_cost_usd=est_cost,
            estimated_latency_ms=int(selected_model_info.latency),
            estimated_savings_pct=est_savings,
            ranked_candidates=tuple(ranked_scores),
            rejected_providers=tuple(rejected_providers),
            alternative_models=tuple(alt_models),
            failover_triggered=failover_triggered,
        )


adaptive_routing_engine = AdaptiveAIRoutingEngine()
